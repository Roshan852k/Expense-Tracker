"""PDF expense statement.

Builds a bank-statement style report: header, summary, category breakdown and
the full transaction list, with page numbers. Uses only reportlab's built-in
Helvetica, so there is no font file to ship. Helvetica has no rupee sign or
non-Latin letters, so amounts are written as "Rs." and any unsupported
character in a note is shown as "?" (the CSV export keeps the original text).
"""
import io
from datetime import date, datetime
from decimal import Decimal
from typing import Iterable, Optional
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.enums import TA_RIGHT
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.pdfgen import canvas
from reportlab.platypus import (
    Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle,
)

INK = colors.HexColor("#222222")
MUTED = colors.HexColor("#666666")
LINE = colors.HexColor("#dddddd")
HEAD_BG = colors.HexColor("#222222")
ZEBRA = colors.HexColor("#f6f6f6")
BOX_BG = colors.HexColor("#f2f4f7")


def _safe(text: Optional[str]) -> str:
    """Latin-1 only (Helvetica), then XML-escaped for Paragraph."""
    text = (text or "").encode("latin-1", "replace").decode("latin-1")
    return escape(text)


def inr(value) -> str:
    """Indian digit grouping: 1234567.5 -> 'Rs. 12,34,567.50'."""
    value = Decimal(value).quantize(Decimal("0.01"))
    sign = "-" if value < 0 else ""
    whole, frac = f"{abs(value):.2f}".split(".")
    if len(whole) > 3:
        head, tail = whole[:-3], whole[-3:]
        groups = []
        while len(head) > 2:
            groups.insert(0, head[-2:])
            head = head[:-2]
        if head:
            groups.insert(0, head)
        whole = ",".join(groups + [tail])
    return f"{sign}Rs. {whole}.{frac}"


def _d(value: date) -> str:
    return value.strftime("%d %b %Y")


def _period(date_from: Optional[date], date_to: Optional[date]) -> str:
    if date_from and date_to:
        return f"{_d(date_from)} to {_d(date_to)}"
    if date_from:
        return f"From {_d(date_from)}"
    if date_to:
        return f"Up to {_d(date_to)}"
    return "All dates"


class _NumberedCanvas(canvas.Canvas):
    """Two-pass canvas so every page can say 'Page x of y'."""

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved = []

    def showPage(self):
        self._saved.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        total = len(self._saved)
        for state in self._saved:
            self.__dict__.update(state)
            self._footer(total)
            super().showPage()
        super().save()

    def _footer(self, total: int):
        width, _ = A4
        self.setStrokeColor(LINE)
        self.line(15 * mm, 14 * mm, width - 15 * mm, 14 * mm)
        self.setFont("Helvetica", 8)
        self.setFillColor(MUTED)
        self.drawString(15 * mm, 9.5 * mm, "Generated by Spend Tracker")
        self.drawRightString(width - 15 * mm, 9.5 * mm, f"Page {self._pageNumber} of {total}")


def build_statement_pdf(
    *,
    user_name: str,
    user_email: str,
    expenses: Iterable,
    date_from: Optional[date] = None,
    date_to: Optional[date] = None,
    category: Optional[str] = None,
) -> bytes:
    rows = list(expenses)
    total = sum((Decimal(e.amount) for e in rows), Decimal("0"))
    count = len(rows)
    average = (total / count) if count else Decimal("0")

    by_cat: dict = {}
    for e in rows:
        c = by_cat.setdefault(e.category, [0, Decimal("0")])
        c[0] += 1
        c[1] += Decimal(e.amount)
    cats = sorted(by_cat.items(), key=lambda kv: kv[1][1], reverse=True)

    base = getSampleStyleSheet()
    title = ParagraphStyle("t", parent=base["Title"], fontName="Helvetica-Bold",
                           fontSize=20, leading=24, alignment=0, textColor=INK, spaceAfter=2)
    sub = ParagraphStyle("s", parent=base["Normal"], fontSize=9.5, leading=13, textColor=MUTED)
    h2 = ParagraphStyle("h2", parent=base["Heading2"], fontName="Helvetica-Bold",
                        fontSize=12, leading=15, textColor=INK, spaceBefore=14, spaceAfter=6)
    cell = ParagraphStyle("c", parent=base["Normal"], fontSize=9, leading=11.5, textColor=INK)
    cell_r = ParagraphStyle("cr", parent=cell, alignment=TA_RIGHT)
    head = ParagraphStyle("h", parent=cell, fontName="Helvetica-Bold", textColor=colors.white)
    head_r = ParagraphStyle("hr", parent=head, alignment=TA_RIGHT)
    big = ParagraphStyle("b", parent=cell, fontName="Helvetica-Bold", fontSize=13, leading=16)
    small = ParagraphStyle("sm", parent=cell, fontSize=8, textColor=MUTED)

    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf, pagesize=A4, leftMargin=15 * mm, rightMargin=15 * mm,
        topMargin=15 * mm, bottomMargin=20 * mm,
        title="Expense Statement", author="Spend Tracker",
    )
    width = A4[0] - 30 * mm
    story = []

    # ---- Header ----
    story.append(Paragraph("Expense Statement", title))
    who = _safe(user_name or user_email)
    story.append(Paragraph(
        f"<b>{who}</b> &nbsp;&middot;&nbsp; {_safe(user_email)}", sub))
    meta = f"Period: <b>{_safe(_period(date_from, date_to))}</b>"
    if category:
        meta += f" &nbsp;&middot;&nbsp; Category: <b>{_safe(category)}</b>"
    story.append(Paragraph(meta, sub))
    story.append(Paragraph(
        f"Generated on {datetime.now().strftime('%d %b %Y, %H:%M')}", sub))
    story.append(Spacer(1, 8))

    # ---- Summary boxes ----
    top = f"{_safe(cats[0][0])}" if cats else "-"
    boxes = Table(
        [[Paragraph("TOTAL SPENT", small), Paragraph("EXPENSES", small),
          Paragraph("AVERAGE", small), Paragraph("TOP CATEGORY", small)],
         [Paragraph(inr(total), big), Paragraph(str(count), big),
          Paragraph(inr(average), big), Paragraph(top, big)]],
        colWidths=[width * 0.31, width * 0.17, width * 0.28, width * 0.24],
    )
    boxes.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), BOX_BG),
        ("LEFTPADDING", (0, 0), (-1, -1), 10), ("RIGHTPADDING", (0, 0), (-1, -1), 6),
        ("TOPPADDING", (0, 0), (-1, 0), 8), ("BOTTOMPADDING", (0, 1), (-1, 1), 9),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
    ]))
    story.append(boxes)

    if not rows:
        story.append(Spacer(1, 24))
        story.append(Paragraph("No expenses were found for this period.", sub))
        doc.build(story, canvasmaker=_NumberedCanvas)
        return buf.getvalue()

    # ---- Category breakdown ----
    story.append(Paragraph("Spending by category", h2))
    data = [[Paragraph("Category", head), Paragraph("Expenses", head_r),
             Paragraph("Amount", head_r), Paragraph("Share", head_r)]]
    for name, (n, amt) in cats:
        share = (amt / total * 100) if total else Decimal("0")
        data.append([Paragraph(_safe(name), cell), Paragraph(str(n), cell_r),
                     Paragraph(inr(amt), cell_r), Paragraph(f"{share:.1f}%", cell_r)])
    t = Table(data, colWidths=[width * 0.40, width * 0.15, width * 0.28, width * 0.17], repeatRows=1)
    t.setStyle(_table_style())
    story.append(t)

    # ---- Transactions ----
    story.append(Paragraph("Transactions", h2))
    data = [[Paragraph("Date", head), Paragraph("Category", head),
             Paragraph("Note", head), Paragraph("Amount", head_r)]]
    for e in rows:
        data.append([Paragraph(_d(e.date), cell), Paragraph(_safe(e.category), cell),
                     Paragraph(_safe(e.note) or "-", cell), Paragraph(inr(e.amount), cell_r)])
    data.append([Paragraph("<b>Total</b>", cell), "", Paragraph(f"{count} expenses", cell),
                 Paragraph(f"<b>{inr(total)}</b>", cell_r)])
    t = Table(data, colWidths=[width * 0.16, width * 0.22, width * 0.37, width * 0.25], repeatRows=1)
    style = _table_style()
    style.add("LINEABOVE", (0, -1), (-1, -1), 1, INK)
    style.add("BACKGROUND", (0, -1), (-1, -1), BOX_BG)
    t.setStyle(style)
    story.append(t)

    doc.build(story, canvasmaker=_NumberedCanvas)
    return buf.getvalue()


def _table_style() -> TableStyle:
    return TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), HEAD_BG),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, ZEBRA]),
        ("LINEBELOW", (0, 1), (-1, -1), 0.25, LINE),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("LEFTPADDING", (0, 0), (-1, -1), 6), ("RIGHTPADDING", (0, 0), (-1, -1), 6),
        ("TOPPADDING", (0, 0), (-1, -1), 5), ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
    ])
